create or replace function public.reclassify_prospect_titles_v1(p_limit integer default 500)
returns integer
language plpgsql
security definer
set search_path = public
set statement_timeout = '60s'
as $$
declare
  v_keywords_updated_at timestamptz;
  v_ids text[];
  v_updated integer := 0;
begin
  select s.keywords_updated_at into v_keywords_updated_at from public.title_classifier_state s where s.id;

  select coalesce(array_agg(t.id), '{}'::text[]) into v_ids
  from (
    select p.id from public.prospects p
    where p.title_classified_at is null or p.title_classified_at < v_keywords_updated_at
    order by p.title_classified_at nulls first
    limit greatest(1, least(coalesce(p_limit, 500), 5000))
  ) t;

  if array_length(v_ids, 1) is null then return 0; end if;

  -- Writes only the derived columns, so the BEFORE UPDATE trigger (which watches
  -- title and company_id) does not fire and re-do the same work.
  update public.prospects p set
    title_seniority = classified.seniority,
    title_department = classified.department,
    title_sub_department = classified.sub_department,
    title_secondary_departments = classified.secondary_departments,
    title_is_former = classified.is_former,
    title_normalized = classified.normalized_title,
    title_top_management = public.title_is_top_management_v1(classified.normalized_title, coalesce(c.name, '')),
    title_classified_at = now()
  from unnest(v_ids) as target(id)
  left join public.prospects source on source.id = target.id
  left join public.companies c on c.id = source.company_id
  cross join lateral public.classify_job_title_v1(coalesce(source.title, ''), coalesce(c.name, '')) classified
  where p.id = target.id;
  get diagnostics v_updated = row_count;

  update public.prospect_index pi set
      title_seniority=p.title_seniority,title_department=p.title_department,
      title_sub_department=p.title_sub_department,title_is_former=p.title_is_former,
      title_normalized=p.title_normalized,title_top_management=p.title_top_management
    from public.prospects p where pi.id=p.id and p.id=any(v_ids)
      and (pi.title_seniority,pi.title_department,pi.title_sub_department,pi.title_is_former,pi.title_normalized,pi.title_top_management)
        is distinct from (p.title_seniority,p.title_department,p.title_sub_department,p.title_is_former,p.title_normalized,p.title_top_management);
    perform public.reindex_prospects(array(
      select id from unnest(v_ids) target(id)
      where not exists(select 1 from public.prospect_index pi where pi.id=target.id)
    ));
  return v_updated;
end;
$$;

-- 5. The filter: __title_top_management, 'yes' or 'no'.
do $patch$
declare
  v_definition text;
  v_anchor text;
begin
  select pg_get_functiondef('public.prospect_filter_sql_v1(text,jsonb)'::regprocedure) into v_definition;
  if position('__title_top_management' in v_definition) = 0 then
    v_anchor := $old$    if field_key = '__icp_unverified' then$old$;
    if (length(v_definition) - length(replace(v_definition, v_anchor, ''))) / length(v_anchor) <> 1 then
      raise exception 'prospect_filter_sql_v1: ICP Unverified anchor is not unique';
    end if;
    execute replace(v_definition, v_anchor,
      $new$    -- Top management, from the job title (20261008110000).
    if field_key = '__title_top_management' then
      if cardinality(raw_values) < 1 or raw_values[1] not in ('yes', 'no') then continue; end if;
      conjuncts := conjuncts || case when raw_values[1] = 'yes' then 'pi.title_top_management' else 'not pi.title_top_management' end;
      continue;
    end if;

    if field_key = '__icp_unverified' then$new$);
  end if;

  select pg_get_functiondef('public.prospect_index_matches_v1(public.prospect_index,text,jsonb)'::regprocedure) into v_definition;
  if position('__title_top_management' in v_definition) = 0 then
    v_anchor := $old$      when filter_item->>'field' = '__icp_unverified' then ($old$;
    if (length(v_definition) - length(replace(v_definition, v_anchor, ''))) / length(v_anchor) <> 1 then
      raise exception 'prospect_index_matches_v1: ICP Unverified anchor is not unique';
    end if;
    execute replace(v_definition, v_anchor,
      $new$      when filter_item->>'field' = '__title_top_management' then (
        coalesce(filter_item->'values'->>0, '') not in ('yes', 'no')
        or (p_row).title_top_management = (filter_item->'values'->>0 = 'yes')
      )
      when filter_item->>'field' = '__icp_unverified' then ($new$);
  end if;
end;
$patch$;

-- 6. Download and upload, as for the seniority and department lists.
create or replace function public.title_keywords_export_v1(p_kind text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case p_kind
    when 'seniority' then (
      select coalesce(jsonb_agg(jsonb_build_object('keyword', k.keyword, 'tier', k.tier, 'notes', k.notes)
                                order by k.token_count desc, k.keyword), '[]'::jsonb)
        from public.title_seniority_keywords k)
    when 'department' then (
      select coalesce(jsonb_agg(jsonb_build_object('keyword', k.keyword, 'department', k.department,
                                                   'sub_department', k.sub_department, 'notes', k.notes)
                                order by k.token_count desc, k.keyword), '[]'::jsonb)
        from public.title_department_keywords k)
    when 'top_management_include' then (
      select coalesce(jsonb_agg(jsonb_build_object('keyword', k.keyword, 'notes', k.notes)
                                order by k.token_count desc, k.keyword), '[]'::jsonb)
        from public.title_top_management_keywords k where k.kind = 'include')
    when 'top_management_exclude' then (
      select coalesce(jsonb_agg(jsonb_build_object('keyword', k.keyword, 'protects', k.notes)
                                order by k.token_count desc, k.keyword), '[]'::jsonb)
        from public.title_top_management_keywords k where k.kind = 'exclude')
  end;
$$;

