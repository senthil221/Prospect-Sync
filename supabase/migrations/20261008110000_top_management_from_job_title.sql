-- Top management: people whose job title says they can take company-wide
-- decisions - founders, owners, CEOs, managing directors, chairmen, partners,
-- general managers and their equivalents in seven languages.
--
-- Asked for on 2026-10-08 with two keyword files, now data/top_management_include.csv
-- (239 keywords) and data/top_management_exclude.csv (1,450). The exclude list
-- exists to stop an include keyword firing inside a longer phrase that is not
-- top management: "vice president" is not a president, "product owner" not an
-- owner, "sales director" and "director of operations" not a company director,
-- "EA to the CEO" not a CEO, "MD Pediatrics" a doctor.
--
-- RULE (title_is_top_management_v1). The same longest-phrase-first scan the
-- seniority classifier uses: every keyword of either list found in the
-- normalized title, longest first, then leftmost; a match whose words were
-- already taken by a longer one is skipped. An exclude match only takes its
-- words; the title is top management when any include match survives. So
-- "vice president" (2 words) takes "president" before "president" (1 word) can
-- fire, while "founder and vice president" is still top management through
-- "founder". As in the seniority scan, a former role ("Former CEO", "Ex
-- Founder") does not count, and "md" does not count at a hospital, clinic or
-- other healthcare company, where it is a medical degree.
--
-- STORAGE. A flag beside the other derived title columns, prospects and
-- prospect_index.title_top_management, written by the same classifier
-- trigger on every insert and title change, and by the reclassify batch. The
-- keyword table bumps title_classifier_state like the other two lists, so
-- seeding it here marks every prospect for reclassification; the classifier
-- re-run (Job titles tab, or deploy/scripts/classify-titles.sh) fills the flag
-- in for existing people. Until it finishes, people not yet re-run read as not
-- top management.
--
-- FILTER. __title_top_management, value 'yes' or 'no', in the People compiler
-- and row matcher.
--
-- LISTS. Both are downloadable and uploadable from the Job titles tab, like the
-- seniority and department lists: title_keywords_export_v1 and
-- apply_title_keywords_v1 gain the kinds top_management_include and
-- top_management_exclude, in the layout of the two files.
-- ---------------------------------------------------------------------------

set local lock_timeout = '10s';

