-- 3. The rule. Takes the title already normalized by classify_job_title_v1.
create or replace function public.title_is_top_management_v1(p_normalized_title text, p_company_name text default '')
returns boolean
language plpgsql
stable
set search_path = public
as $$
declare
  v_tokens text[];
  v_count integer;
  v_healthcare boolean;
  v_consumed boolean[];
  v_overlap boolean;
  v_position integer;
  match_row record;
begin
  v_tokens := string_to_array(coalesce(p_normalized_title, ''), ' ');
  v_count := coalesce(array_length(v_tokens, 1), 0);
  if v_count = 0 or v_tokens[1] = '' or v_tokens[1] in ('former', 'ex', 'retired', 'past') then
    return false;
  end if;
  -- The seniority classifier's own healthcare test, so "md" means the same thing in both.
  v_healthcare := coalesce(p_company_name, '') ~* '(hospital|clinic|medical|healthcare|health care|diagnostic|patholog|labs\y|laborator)';

  v_consumed := array_fill(false, array[v_count]);
  for match_row in
    with ngram as (
      select start_pos.value as start_pos, len.value as len,
        array_to_string(v_tokens[start_pos.value : start_pos.value + len.value - 1], ' ') as phrase
      from generate_series(1, v_count) as start_pos(value)
      cross join generate_series(1, least(v_count, 8)) as len(value)
      where start_pos.value + len.value - 1 <= v_count
    )
    select n.start_pos, n.len, k.kind
    from ngram n
    join public.title_top_management_keywords k on k.keyword = n.phrase
    where not (v_healthcare and n.phrase = 'md')
    order by n.len desc, n.start_pos asc
  loop
    select bool_or(v_consumed[position.value]) into v_overlap
    from generate_series(match_row.start_pos, match_row.start_pos + match_row.len - 1) as position(value);
    if coalesce(v_overlap, false) then continue; end if;
    for v_position in match_row.start_pos .. match_row.start_pos + match_row.len - 1 loop
      v_consumed[v_position] := true;
    end loop;
    -- "Founder (former MD)": a former marker right before the keyword voids it.
    if match_row.kind = 'include'
       and not (match_row.start_pos > 1 and v_tokens[match_row.start_pos - 1] in ('former', 'ex', 'retired', 'past')) then
      return true;
    end if;
  end loop;
  return false;
end;
$$;

